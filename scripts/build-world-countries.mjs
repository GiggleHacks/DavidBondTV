#!/usr/bin/env node
// Generate public/js/world-countries.js — one SVG path per country, projected
// into the same 0..360 × 0..180 equirectangular space as world-data.js project()
// (x = lng+180, y = 90−lat). The 2D traffic map (admin-map-2d.js) draws these as
// individual <path>s so it can show borders, choropleth fills, and name labels —
// unlike WORLD_LAND (world-map-paths.js), which is one merged blob for the globe.
//
// Source: Natural Earth 110m admin-0 countries (public domain). This is a one-time
// generation that needs network access; the emitted artifact is committed and the
// runtime imports it offline, exactly like world-map-paths.js.
//
//   node scripts/build-world-countries.mjs
//
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SRC = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'js', 'world-countries.js');

// Equirectangular projection — must match world-data.js project().
const px = (lng) => lng + 180;
const py = (lat) => 90 - lat;
const r2 = (n) => Math.round(n * 100) / 100; // 0.01° ≈ 1km — plenty for a world map

// Build an SVG path from a GeoJSON Polygon/MultiPolygon, projecting every vertex.
// Returns { d, area, cx, cy } where cx,cy is the centroid of the largest ring
// (used as the label anchor) and area is that ring's |signed area| in deg².
function geomToPath(geom) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates]
    : geom.type === 'MultiPolygon' ? geom.coordinates : [];
  let d = '';
  let best = { area: 0, cx: 0, cy: 0 };
  for (const poly of polys) {
    poly.forEach((ring, ri) => {
      if (ring.length < 3) return;
      d += ring.map(([lng, lat], i) => `${i ? 'L' : 'M'}${r2(px(lng))} ${r2(py(lat))}`).join('') + 'Z';
      if (ri === 0) {
        // Shoelace area + centroid of the outer ring, in projected space.
        let a = 0, cx = 0, cy = 0;
        for (let i = 0, n = ring.length; i < n; i++) {
          const [x1, y1] = [px(ring[i][0]), py(ring[i][1])];
          const [x2, y2] = [px(ring[(i + 1) % n][0]), py(ring[(i + 1) % n][1])];
          const cross = x1 * y2 - x2 * y1;
          a += cross; cx += (x1 + x2) * cross; cy += (y1 + y2) * cross;
        }
        a *= 0.5;
        const abs = Math.abs(a);
        if (abs > best.area && a !== 0) best = { area: abs, cx: cx / (6 * a), cy: cy / (6 * a) };
      }
    });
  }
  return { d, ...best };
}

const res = await fetch(SRC);
if (!res.ok) { console.error('fetch failed', res.status); process.exit(1); }
const geo = JSON.parse(await res.text());

const out = [];
let skipped = 0;
for (const f of geo.features) {
  const p = f.properties || {};
  // ISO_A2_EH carries codes for de-facto states where ISO_A2 is '-99' (e.g. France, Norway, Kosovo).
  let cc = (p.ISO_A2_EH && p.ISO_A2_EH !== '-99') ? p.ISO_A2_EH
    : (p.ISO_A2 && p.ISO_A2 !== '-99') ? p.ISO_A2 : null;
  const name = p.NAME || p.ADMIN || p.NAME_LONG || '';
  const { d, cx, cy, area } = geomToPath(f.geometry || {});
  if (!d) { skipped++; continue; }
  out.push({ cc: cc ? cc.toUpperCase() : null, name, d, cx: r2(cx), cy: r2(cy), area: r2(area) });
}
// Largest countries first so labels for big nations win the de-clutter pass.
out.sort((a, b) => b.area - a.area);

const banner = `// Auto-generated by scripts/build-world-countries.mjs — DO NOT EDIT BY HAND.
// Natural Earth 110m admin-0 countries (public domain), projected to the 0..360 × 0..180
// equirectangular viewBox used by admin-map-2d.js (x = lng+180, y = 90−lat). Each entry:
//   { cc, name, d, cx, cy, area } — cc: ISO-2 (null for disputed/uncoded), d: SVG path,
//   cx,cy: label anchor (centroid of largest ring), area: that ring's area in deg².
`;
const body = out.map((c) => '  ' + JSON.stringify(c)).join(',\n');
writeFileSync(OUT, `${banner}export const WORLD_COUNTRIES = [\n${body},\n];\n`);
console.log(`wrote ${out.length} countries (skipped ${skipped} empty) → ${OUT}`);
