export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}

// Render an icon as an <svg> string. opts.size sets width/height (default 1em so
// it tracks font-size). opts.cls adds classes; opts.strokeWidth overrides weight.
export function icon(name, opts = {}) {
  const inner = PATHS[name];
  if (!inner) return '';
  const size = opts.size || '1em';
  const cls = opts.cls ? ` class="${opts.cls}"` : '';
  const sw = opts.strokeWidth || 2;
  return `<svg${cls} width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${inner}</svg>`;
}
