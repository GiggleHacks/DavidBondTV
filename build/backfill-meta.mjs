// Re-generates title + description for every entry already in the manifest by
// running the local analyzer over the matching source clip, matched BY id (not
// index). Preserves id/duration/durLabel/thumb/uploaded/preview. Writes the
// manifest atomically and de-dups any colliding titles. Degrades gracefully:
// if ffmpeg isn't available, titles fall back to metadata-only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyze, ensureUniqueTitle, parseDjiName } from '../lib/analyze.mjs';
import { hasFfmpeg } from '../lib/media.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const SRC = 'D:/Local/Traveling/Bangkok 2026/shopping jess barbie';
const { MANIFEST } = await import('../lib/paths.js');

if (!hasFfmpeg()) {
  console.warn('⚠  ffmpeg not found — titles will be metadata-only (no visual signal).');
}

// Map id → source file path (the source filenames keep their original extension).
const srcFiles = fs.readdirSync(SRC).filter((f) => /\.(mp4|mov|m4v)$/i.test(f));
const byId = new Map(srcFiles.map((f) => [f.replace(/\.[^.]+$/, ''), path.join(SRC, f)]));

const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf-8'));
const taken = new Set();

for (let i = 0; i < manifest.length; i++) {
  const entry = manifest[i];
  const file = byId.get(entry.id);
  process.stdout.write(`[${i + 1}/${manifest.length}] ${entry.id}... `);

  if (!file) {
    console.log('SKIP (no source file)');
    taken.add(entry.title);
    continue;
  }

  const mtime = fs.statSync(file).mtimeMs;
  const { title, description, autoGenerated } = await analyze(file, { id: entry.id, mtime });
  // Natural collision disambiguator: the clip's capture clock time.
  const d = parseDjiName(entry.id)?.date || new Date(mtime);
  const clock = d.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit' });
  const unique = ensureUniqueTitle(title, clock, taken);
  taken.add(unique);

  entry.title = unique;
  entry.description = description;
  entry.autoGenerated = autoGenerated;
  console.log(`"${unique}"`);
}

// Atomic write: temp file in the same dir, then rename.
const tmp = `${MANIFEST}.tmp`;
fs.writeFileSync(tmp, JSON.stringify(manifest, null, 2));
fs.renameSync(tmp, MANIFEST);
console.log(`\nRewrote ${manifest.length} titles/descriptions in videos.json`);
